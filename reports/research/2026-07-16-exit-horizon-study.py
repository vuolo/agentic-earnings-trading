def agg(rows, title):
    n = len(rows)
    print(f"\n=== {title} (n={n}) ===")
    print(f"{'exit':10}{'mean':>8}{'median':>8}{'beats open':>12}")
    open_vals = {id(r): r["vals"][0] for r in rows}
    for i, c in enumerate(COLS):
        vals = [(r["vals"][i], open_vals[id(r)]) for r in rows if r["vals"][i] is not None]
        if not vals:
            continue
        vs = sorted(v for v, _ in vals)
        mean = sum(vs) / len(vs)
        med = vs[len(vs)//2] if len(vs) % 2 else (vs[len(vs)//2-1] + vs[len(vs)//2]) / 2
        beats = sum(v > o for v, o in vals)
        extra = f"{beats}/{len(vals)}" if i else "-"
        print(f"{c:10}{mean:8.2f}{med:8.2f}{extra:>12}")

